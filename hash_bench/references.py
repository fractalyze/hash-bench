_BY_NAME = {ref.name: ref for ref in _REFERENCES}


def names() -> tuple[str, ...]:
    return tuple(_BY_NAME)


def get(name: str) -> Reference:
    if name not in _BY_NAME:
        raise KeyError(f"no such reference: {name}; have {', '.join(_BY_NAME)}")
    return _BY_NAME[name]


def is_reference(arm: str) -> bool:
    return arm in _BY_NAME


def rows(ref: Reference, selected: tuple[str, ...] = ()) -> Iterator[registry.HashSpec]:
    """The registry rows this reference implements, in table order.

    A reference covers the hashes its codebase implements and no others, so a
    sweep that asks for every hash gets reference rows only where there is one.
    Asking for a hash a reference does not implement is not an error either: the
    sweep runs several arms over one hash list.
    """
    for spec in registry.rows(selected):
        if ref.covers(spec.name):
            yield spec
