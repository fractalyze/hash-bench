"""The external CPU references, as arms of the same sweep.

A reference is a pinned implementation of a hash the registry already carries,
reached through `ctypes` instead of through frx. It is an ARM rather than a
table of its own, because the question the harness exists to answer — is the
generic path at the frontier — is a comparison, and a comparison is only sound
when both sides are the same measurement. So a reference produces a
`registry.Call` of exactly the shape a hash-frx arm produces, is timed by the
same `timing.measure`, and is divided by the same leg `Peaks`.

Two things a reference row does differently, both recorded in the row rather
than argued about here:

- **It carries its provenance.** `results.Row.reference` holds the revision, the
  upstream implementation selected, and the flags the shim was compiled with,
  generated by the build that produced the shared object
  (`reference/defs.bzl`). A reference number means nothing without them.
- **It is dispatched synchronously.** A native call returns complete, so there
  is nothing to block on; `method.dispatch` says so, and every other field of
  the method — warmup, reps, the calibration target, the statistic, the timer —
  is the one the hash-frx rows used.

References run on the CPU legs only. They are the CPU frontier; a GPU reference
is a different set of codebases and a different pin.

The input a reference hashes is built to the same counting pattern
`registry.HashSpec.call` builds, so the two sides consume identical bytes and
`testing/references_test.py` can hold the reference to hash-frx's own output.
That cross-check is what makes the row a reference rather than an unrelated
program that happens to be fast.
"""

from __future__ import annotations

import ctypes
import dataclasses
import functools
import json
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

from hash_bench import registry

# References are the CPU frontier, so a reference arm is offered on the CPU legs
# and on no others. Named here rather than read off `backends` because it is a
# property of what these codebases are, not of what this machine has.
CPU_LEGS: tuple[str, ...] = ("cpu-1core", "cpu")


def _artifact(name: str) -> Path:
    """A file the reference build produced, out of the runfiles tree.

    Two candidate roots, for the reason `machine._pinned_hash_frx_commit`
    carries in full: a runfiles entry may be a symlink back into the source
    tree, and the shared objects exist only under the runfiles root, never
    beside the checked-in sources. Resolving first would look for them in the
    source tree and find nothing.
    """
    here = Path(__file__)
    for root in (here.parent, here.resolve().parent):
        candidate = root / "reference" / name
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        f"hash_bench/reference/{name} is not in the runfiles tree; the "
        "reference arms need `//hash_bench/reference:<name>` as data"
    )


@dataclasses.dataclass(frozen=True)
class Provenance:
    """What the build put into one reference's shared object.

    Read back from the JSON `reference/defs.bzl` generates off the same values
    the build applied, so this is the build's account of itself rather than a
    second copy maintained by hand.
    """

    reference: str
    # The shared object this describes. Named rather than derived, so a
    # reference can be built by whichever rule suits its language.
    library: str
    revision: str
    source: str
    implementation: str
    # The Bazel compilation mode the whole reference was built under — the
    # shim AND every upstream target beneath it. The hash-frx side arrives as
    # an optimised wheel, so a reference built at the default mode would be an
    # unoptimised upstream wearing the same name.
    compilation_mode: str
    # A C shim's own copts and linkopts, or the rustc flags the Rust reference
    # applies to its shim and every crate under it — which is what decides the
    # upstream's packed field, a `target_feature` gate read per crate.
    flags: tuple[str, ...]
    note: str | None
    # What the loaded library says about itself at run time, where it offers an
    # answer. Several of these upstreams select their kernel from CPUID rather
    # than from a compile flag, so the flags alone do not say what ran; this is
    # asked of the process that is about to produce the rows. None where the
    # upstream's selection is entirely a build-time choice.
    runtime_dispatch: str | None = None

    def to_json(self) -> dict[str, Any]:
        d = dataclasses.asdict(self)
        d["flags"] = list(self.flags)
        return d


@dataclasses.dataclass(frozen=True)
class Entry:
    """One (reference, hash) pair: the symbol to call and how to shape the call.

    `build` takes the loaded library and a batch and returns the `Call` the
    driver times, so the argument marshalling for a permutation and for a byte
    hash stay next to the C signatures they mirror.
    """

    hash: str
    symbol: str
    build: Callable[[ctypes.CDLL, registry.HashSpec, int], registry.Call]


@dataclasses.dataclass(frozen=True)
class Reference:
    """One pinned external implementation, covering one or more registry rows."""

    name: str
    entries: tuple[Entry, ...]

    @functools.cached_property
    def _by_hash(self) -> dict[str, Entry]:
        return {e.hash: e for e in self.entries}

    def hashes(self) -> tuple[str, ...]:
        return tuple(self._by_hash)

    def covers(self, hash_name: str) -> bool:
        return hash_name in self._by_hash

    @functools.cached_property
    def _payload(self) -> dict[str, Any]:
        return json.loads(_artifact(f"{self.name}.provenance.json").read_text())

    @functools.cached_property
    def provenance(self) -> Provenance:
        payload = self._payload
        return Provenance(
            reference=payload["reference"],
            library=payload["library"],
            revision=payload["revision"],
            source=payload["source"],
            implementation=payload["implementation"],
            compilation_mode=payload["compilation_mode"],
            flags=tuple(payload["flags"]),
            note=payload["note"],
            runtime_dispatch=self._runtime_dispatch(),
        )

    def _runtime_dispatch(self) -> str | None:
        """Ask the loaded library what it is, where it can answer.

        By convention the shim exports `hash_bench_<name>_capabilities`; a
        reference whose kernel is fixed at build time exports none, and its
        absence is the answer rather than a failure.
        """
        try:
            described = getattr(self.library, f"hash_bench_{self.name}_capabilities")
        except AttributeError:
            return None
        described.argtypes = []
        described.restype = ctypes.c_char_p
        return described().decode()

    @functools.cached_property
    def library(self) -> ctypes.CDLL:
        """The shared object, loaded once per process.

        `RTLD_GLOBAL` is not asked for: each shim links its upstream statically,
        so two references loaded into one worker cannot collide over a symbol.
        """
        return ctypes.CDLL(str(_artifact(self._payload["library"])))

    def symbol(self, hash_name: str) -> str:
        """The entry point a row for `hash_name` calls — the row's `kernels`,
        and the same kind of evidence a hash-frx row reads off its module."""
        return self._by_hash[hash_name].symbol

    def call(self, spec: registry.HashSpec, batch: int) -> registry.Call:
        entry = self._by_hash[spec.name]
        return entry.build(self.library, spec, batch)


def _as_ptr(array: Any) -> ctypes.c_void_p:
    return ctypes.c_void_p(array.ctypes.data)


def _permutation_call(
    lib: ctypes.CDLL, spec: registry.HashSpec, batch: int, symbol: str
) -> registry.Call:
    """`void f(const void *in, void *out, size_t batch)` over a batch of states.

    The state array is built to the same counting pattern and the same
    `(batch, width)` dtype as `HashSpec.call`, which is both what makes the two
    rows' traffic equal and what lets the cross-check compare outputs directly.
    """
    import numpy as np

    unit = spec.build()
    x = np.arange(batch * unit.width, dtype=unit.dtype).reshape(batch, unit.width)
    out = np.empty_like(x)
    fn = getattr(lib, symbol)
    fn.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_size_t]
    fn.restype = None
    out_ptr = _as_ptr(out)

    def run(state: Any) -> Any:
        fn(_as_ptr(state), out_ptr, batch)
        return out

    ops = spec.op_model(unit) if spec.op_model is not None else None
    return registry.Call(
        fn=run,
        x=x,
        hashes=batch,
        bytes_moved=registry.nbytes(x) + registry.nbytes(out),
        ops=ops,
        ops_dtype=spec.arith_dtype(unit) if ops else None,
    )


def _byte_hash_call(
    lib: ctypes.CDLL, spec: registry.HashSpec, batch: int, symbol: str
) -> registry.Call:
    """`void f(const void *msg, size_t msg_bytes, void *out, size_t batch)`.

    The digest size comes from the hash-frx row rather than from a constant
    here, so a reference cannot quietly write a different number of bytes than
    the row it is compared against.
    """
    import numpy as np

    unit = spec.build()
    msg = np.arange(batch * spec.message_bytes, dtype=np.uint8).reshape(
        batch, spec.message_bytes
    )
    out = np.empty((batch, unit.digest_size), dtype=np.uint8)
    fn = getattr(lib, symbol)
    fn.argtypes = [
        ctypes.c_void_p,
        ctypes.c_size_t,
        ctypes.c_void_p,
        ctypes.c_size_t,
    ]
    fn.restype = None
    out_ptr = _as_ptr(out)

    def run(message: Any) -> Any:
        fn(_as_ptr(message), spec.message_bytes, out_ptr, batch)
        return out

    return registry.Call(
        fn=run,
        x=msg,
        hashes=batch,
        bytes_moved=registry.nbytes(msg) + registry.nbytes(out),
        ops=None,
        ops_dtype=None,
    )


def _permutation(hash_name: str, symbol: str) -> Entry:
    return Entry(
        hash=hash_name,
        symbol=symbol,
        build=lambda lib, spec, batch: _permutation_call(lib, spec, batch, symbol),
    )


def _byte_hash(hash_name: str, symbol: str) -> Entry:
    return Entry(
        hash=hash_name,
        symbol=symbol,
        build=lambda lib, spec, batch: _byte_hash_call(lib, spec, batch, symbol),
    )


