"""The external references, as arms of the same sweep.

A reference is a pinned implementation of a hash the registry already carries,
reached through `ctypes` instead of through frx. It is an ARM rather than a
table of its own, because the question the harness exists to answer — is the
generic path at the frontier — is a comparison, and a comparison is only sound
when both sides are the same measurement. So a reference produces a
`registry.Call` of exactly the shape a hash-frx arm produces, is timed by the
same `timing.measure`, and is divided by the same leg `Peaks`.

Two things a reference row does differently, both recorded in the row rather
than argued about here:

- **It carries its provenance.** `results.Row.reference` holds the revision, the
  upstream implementation selected, and the flags the shim was compiled with,
  generated by the build that produced the shared object
  (`reference/defs.bzl`). A reference number means nothing without them.
- **It is dispatched the way its code runs.** A native CPU call returns
  complete, so there is nothing to block on, and `method.dispatch` says so. A
  CUDA reference launches onto a stream and returns before its kernel ends, so
  it is timed as a hash-frx GPU row is — `iters` launches, one block at the end
  — with the stream's synchronize as the block. Every other field of the method
  is the one the hash-frx rows used.

A reference is offered on the legs its code targets: the CPU references on both
CPU legs, a CUDA reference on the GPU leg. A CUDA reference's input and output
live in device memory (`DeviceArray`), as a hash-frx GPU row's do, so a timed
call moves nothing across the bus.

The input a reference hashes is built to the same counting pattern
`registry.HashSpec.call` builds, so the two sides consume identical bytes and
`testing/references_test.py` can hold the reference to hash-frx's own output.
That cross-check is what makes the row a reference rather than an unrelated
program that happens to be fast.
"""

from __future__ import annotations

import ctypes
import dataclasses
import functools
import json
import math
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

from hash_bench import registry, timing

# The legs a reference is offered on, by what its code targets. Named here
# rather than read off `backends` because it is a property of what these
# codebases are, not of what this machine has.
_CPU_LEGS: tuple[str, ...] = ("cpu-1core", "cpu")
_GPU_LEGS: tuple[str, ...] = ("gpu",)


def _artifact(name: str) -> Path:
    """A file the reference build produced, out of the runfiles tree.

    Two candidate roots, for the reason `machine._pinned_hash_frx_commit`
    carries in full: a runfiles entry may be a symlink back into the source
    tree, and the shared objects exist only under the runfiles root, never
    beside the checked-in sources. Resolving first would look for them in the
    source tree and find nothing.
    """
    here = Path(__file__)
    for root in (here.parent, here.resolve().parent):
        candidate = root / "reference" / name
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        f"hash_bench/reference/{name} is not in the runfiles tree; the "
        "reference arms need `//hash_bench/reference:<name>` as data"
    )


@dataclasses.dataclass(frozen=True)
class Provenance:
    """What the build put into one reference's shared object.

    Read back from the JSON `reference/defs.bzl` generates off the same values
    the build applied, so this is the build's account of itself rather than a
    second copy maintained by hand.
    """

    reference: str
    # The shared object this describes. Named rather than derived, so a
    # reference can be built by whichever rule suits its language.
    library: str
    revision: str
    source: str
    implementation: str
    # The Bazel compilation mode the whole reference was built under — the
    # shim AND every upstream target beneath it. The hash-frx side arrives as
    # an optimised wheel, so a reference built at the default mode would be an
    # unoptimised upstream wearing the same name.
    compilation_mode: str
    # A C shim's own copts and linkopts, the rustc flags the Rust reference
    # applies to its shim and every crate under it — which is what decides the
    # upstream's packed field, a `target_feature` gate read per crate — or a
    # CUDA shim's nvcc flags and the architectures setting it was built under.
    flags: tuple[str, ...]
    # The patches applied to the pinned upstream before it compiled. Empty for
    # an upstream measured as released; otherwise the revision alone does not
    # name what ran.
    patches: tuple[str, ...]
    note: str | None
    # What the loaded library says about itself at run time, where it offers an
    # answer. Several CPU upstreams select their kernel from CPUID rather than
    # from a compile flag, so the flags alone do not say what ran; a CUDA shim
    # reports the nvcc and architectures that built its kernel and the device
    # and driver it found. Asked of the process about to produce the rows. None
    # where the upstream's selection is entirely a build-time choice.
    runtime_dispatch: str | None = None

    def to_json(self) -> dict[str, Any]:
        d = dataclasses.asdict(self)
        d["flags"] = list(self.flags)
        d["patches"] = list(self.patches)
        return d


class _Cuda:
    """The device-buffer ABI `reference/gpu.h` declares, over one CUDA shim.

    Every entry point returns a `cudaError_t`, and a nonzero one is raised with
    the runtime's own description: a failed launch still returns, and a row
    timing it would time nothing.
    """

    _SIGNATURES = {
        "hash_bench_gpu_device_count": [ctypes.POINTER(ctypes.c_int)],
        "hash_bench_gpu_alloc": [ctypes.POINTER(ctypes.c_void_p), ctypes.c_size_t],
        "hash_bench_gpu_free": [ctypes.c_void_p],
        "hash_bench_gpu_upload": [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_size_t],
        "hash_bench_gpu_download": [
            ctypes.c_void_p,
            ctypes.c_void_p,
            ctypes.c_size_t,
        ],
        "hash_bench_gpu_synchronize": [],
    }

    def __init__(self, lib: ctypes.CDLL) -> None:
        self._lib = lib
        for name, argtypes in self._SIGNATURES.items():
            fn = getattr(lib, name)
            fn.argtypes = argtypes
            fn.restype = ctypes.c_int
        lib.hash_bench_gpu_error_string.argtypes = [ctypes.c_int]
        lib.hash_bench_gpu_error_string.restype = ctypes.c_char_p

    def check(self, status: int, what: str) -> None:
        if status != 0:
            reason = self._lib.hash_bench_gpu_error_string(status).decode()
            raise RuntimeError(f"{what}: {reason}")

    def device_count(self) -> int:
        """How many devices the runtime sees. No driver or no device is an
        answer of zero rather than a failure: it is how a host without a GPU
        finds out."""
        count = ctypes.c_int(0)
        status = self._lib.hash_bench_gpu_device_count(ctypes.byref(count))
        return count.value if status == 0 else 0

    def alloc(self, nbytes: int) -> int:
        ptr = ctypes.c_void_p()
        self.check(self._lib.hash_bench_gpu_alloc(ctypes.byref(ptr), nbytes), "alloc")
        return ptr.value or 0

    def free(self, ptr: int) -> None:
        # Unchecked: it runs from a finalizer, where there is no row to fail.
        self._lib.hash_bench_gpu_free(ptr)

    def upload(self, ptr: int, host: Any) -> None:
        self.check(
            self._lib.hash_bench_gpu_upload(ptr, host.ctypes.data, host.nbytes),
            "upload",
        )

    def download(self, host: Any, ptr: int) -> None:
        self.check(
            self._lib.hash_bench_gpu_download(host.ctypes.data, ptr, host.nbytes),
            "download",
        )

    def synchronize(self, _out: Any) -> None:
        """Wait for every launch on the reference's stream — a `timing.Blocker`."""
        self.check(self._lib.hash_bench_gpu_synchronize(), "synchronize")


class DeviceArray:
    """A batch in device memory that a CUDA reference's shim allocated.

    It carries the `shape`, `dtype` and `size` a host array would, so its
    traffic is read off it by the same `registry.nbytes`. Converting it to numpy
    copies it back, which is how the cross-check reads a result, outside any
    timed region.
    """

    def __init__(self, cuda: _Cuda, shape: tuple[int, ...], dtype: Any) -> None:
        import numpy as np

        self.shape = tuple(shape)
        self.dtype = np.dtype(dtype)
        self.size = math.prod(self.shape)
        self._cuda = cuda
        self.ptr = cuda.alloc(self.size * self.dtype.itemsize)

    @classmethod
    def from_host(cls, cuda: _Cuda, host: Any) -> DeviceArray:
        array = cls(cuda, host.shape, host.dtype)
        cuda.upload(array.ptr, host)
        return array

    def __array__(self, dtype: Any = None, copy: bool | None = None) -> Any:
        import numpy as np

        host = np.empty(self.shape, dtype=self.dtype)
        self._cuda.download(host, self.ptr)
        return host if dtype is None else host.astype(dtype)

    def __del__(self) -> None:
        if getattr(self, "ptr", 0):
            self._cuda.free(self.ptr)
            self.ptr = 0


@dataclasses.dataclass(frozen=True)
class Entry:
    """One (reference, hash) pair: the symbol to call and how to shape the call.

    `build` takes the reference and a batch and returns the `Call` the driver
    times, so the argument marshalling for a permutation and for a byte hash
    stay next to the C signatures they mirror.
    """

    hash: str
    symbol: str
    build: Callable[[Reference, registry.HashSpec, int], registry.Call]


@dataclasses.dataclass(frozen=True)
class Reference:
    """One pinned external implementation, covering one or more registry rows."""

    name: str
    entries: tuple[Entry, ...]
    # Whether the code is CUDA. It decides the legs the reference is offered on
    # and what a rep waits for before its clock stops.
    gpu: bool = False

    @functools.cached_property
    def _by_hash(self) -> dict[str, Entry]:
        return {e.hash: e for e in self.entries}

    def hashes(self) -> tuple[str, ...]:
        return tuple(self._by_hash)

    def covers(self, hash_name: str) -> bool:
        return hash_name in self._by_hash

    @property
    def legs(self) -> tuple[str, ...]:
        return _GPU_LEGS if self.gpu else _CPU_LEGS

    def dispatched(self, method: timing.Method) -> timing.Method:
        """The driver's method as this reference's calls are dispatched: a CUDA
        launch is asynchronous like a hash-frx call, a native call is not."""
        return method if self.gpu else method.synchronous()

    @property
    def block(self) -> timing.Blocker:
        """What a rep waits on before its clock stops: the stream a CUDA
        reference launched onto, or nothing for a native call, which has
        returned its result already."""
        return self.cuda.synchronize if self.gpu else timing.block_none

    @functools.cached_property
    def cuda(self) -> _Cuda:
        if not self.gpu:
            raise TypeError(f"{self.name} is not a CUDA reference")
        return _Cuda(self.library)

    @functools.cached_property
    def _payload(self) -> dict[str, Any]:
        return json.loads(_artifact(f"{self.name}.provenance.json").read_text())

    @functools.cached_property
    def provenance(self) -> Provenance:
        payload = self._payload
        return Provenance(
            reference=payload["reference"],
            library=payload["library"],
            revision=payload["revision"],
            source=payload["source"],
            implementation=payload["implementation"],
            compilation_mode=payload["compilation_mode"],
            flags=tuple(payload["flags"]),
            patches=tuple(payload["patches"]),
            note=payload["note"],
            runtime_dispatch=self._runtime_dispatch(),
        )

    def _runtime_dispatch(self) -> str | None:
        """Ask the loaded library what it is, where it can answer.

        By convention the shim exports `hash_bench_<name>_capabilities`; a
        reference whose kernel is fixed at build time exports none, and its
        absence is the answer rather than a failure.
        """
        try:
            described = getattr(self.library, f"hash_bench_{self.name}_capabilities")
        except AttributeError:
            return None
        described.argtypes = []
        described.restype = ctypes.c_char_p
        return described().decode()

    @functools.cached_property
    def library(self) -> ctypes.CDLL:
        """The shared object, loaded once per process.

        `RTLD_GLOBAL` is not asked for: each shim links its upstream statically,
        so two references loaded into one worker cannot collide over a symbol.
        """
        return ctypes.CDLL(str(_artifact(self._payload["library"])))

    def symbol(self, hash_name: str) -> str:
        """The entry point a row for `hash_name` calls — the row's `kernels`,
        and the same kind of evidence a hash-frx row reads off its module."""
        return self._by_hash[hash_name].symbol

    def call(self, spec: registry.HashSpec, batch: int) -> registry.Call:
        entry = self._by_hash[spec.name]
        return entry.build(self, spec, batch)


def _as_ptr(array: Any) -> ctypes.c_void_p:
    return ctypes.c_void_p(array.ctypes.data)


def _states(unit: Any, batch: int) -> Any:
    """The `(batch, width)` states `HashSpec.call` builds, on the host. Same
    counting pattern and dtype, which is both what makes the two rows' traffic
    equal and what lets the cross-check compare outputs directly."""
    import numpy as np

    return np.arange(batch * unit.width, dtype=unit.dtype).reshape(batch, unit.width)


def _op_model(spec: registry.HashSpec, unit: Any) -> tuple[Any, Any]:
    """The row's op model and the dtype it counts in, or (None, None)."""
    ops = spec.op_model(unit) if spec.op_model is not None else None
    return ops, (spec.arith_dtype(unit) if ops else None)


def _permutation_call(
    lib: ctypes.CDLL, spec: registry.HashSpec, batch: int, symbol: str
) -> registry.Call:
    """`void f(const void *in, void *out, size_t batch)` over a batch of states."""
    import numpy as np

    unit = spec.build()
    x = _states(unit, batch)
    out = np.empty_like(x)
    fn = getattr(lib, symbol)
    fn.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_size_t]
    fn.restype = None
    out_ptr = _as_ptr(out)

    def run(state: Any) -> Any:
        fn(_as_ptr(state), out_ptr, batch)
        return out

    ops, ops_dtype = _op_model(spec, unit)
    return registry.Call(
        fn=run,
        x=x,
        hashes=batch,
        bytes_moved=registry.nbytes(x) + registry.nbytes(out),
        ops=ops,
        ops_dtype=ops_dtype,
    )


def _device_permutation_call(
    ref: Reference, spec: registry.HashSpec, batch: int, symbol: str
) -> registry.Call:
    """`cudaError_t f(const void *in, void *out, size_t batch)` over device buffers.

    The states are uploaded once, when the call is built, so a timed call only
    launches.
    """
    unit = spec.build()
    host = _states(unit, batch)
    cuda = ref.cuda
    x = DeviceArray.from_host(cuda, host)
    out = DeviceArray(cuda, host.shape, host.dtype)
    fn = getattr(ref.library, symbol)
    fn.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_size_t]
    fn.restype = ctypes.c_int

    def run(state: DeviceArray) -> DeviceArray:
        cuda.check(fn(state.ptr, out.ptr, batch), symbol)
        return out

    ops, ops_dtype = _op_model(spec, unit)
    return registry.Call(
        fn=run,
        x=x,
        hashes=batch,
        bytes_moved=registry.nbytes(x) + registry.nbytes(out),
        ops=ops,
        ops_dtype=ops_dtype,
    )


def _byte_hash_call(
    lib: ctypes.CDLL, spec: registry.HashSpec, batch: int, symbol: str
) -> registry.Call:
    """`void f(const void *msg, size_t msg_bytes, void *out, size_t batch)`.

    The digest size comes from the hash-frx row rather than from a constant
    here, so a reference cannot quietly write a different number of bytes than
    the row it is compared against.
    """
    import numpy as np

    unit = spec.build()
    msg = np.arange(batch * spec.message_bytes, dtype=np.uint8).reshape(
        batch, spec.message_bytes
    )
    out = np.empty((batch, unit.digest_size), dtype=np.uint8)
    fn = getattr(lib, symbol)
    fn.argtypes = [
        ctypes.c_void_p,
        ctypes.c_size_t,
        ctypes.c_void_p,
        ctypes.c_size_t,
    ]
    fn.restype = None
    out_ptr = _as_ptr(out)

    def run(message: Any) -> Any:
        fn(_as_ptr(message), spec.message_bytes, out_ptr, batch)
        return out

    return registry.Call(
        fn=run,
        x=msg,
        hashes=batch,
        bytes_moved=registry.nbytes(msg) + registry.nbytes(out),
        ops=None,
        ops_dtype=None,
    )


def _permutation(hash_name: str, symbol: str) -> Entry:
    return Entry(
        hash=hash_name,
        symbol=symbol,
        build=lambda ref, spec, batch: _permutation_call(
            ref.library, spec, batch, symbol
        ),
    )


def _device_permutation(hash_name: str, symbol: str) -> Entry:
    return Entry(
        hash=hash_name,
        symbol=symbol,
        build=lambda ref, spec, batch: _device_permutation_call(
            ref, spec, batch, symbol
        ),
    )


def _byte_hash(hash_name: str, symbol: str) -> Entry:
    return Entry(
        hash=hash_name,
        symbol=symbol,
        build=lambda ref, spec, batch: _byte_hash_call(
            ref.library, spec, batch, symbol
        ),
    )


